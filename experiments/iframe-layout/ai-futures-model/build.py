"""Builds the AI Futures Model demo widgets into self-contained HTML files in out/.

Each widget gets the shared CSS inlined and loads the ET Book font from a CDN (the font used to be
inlined too, but 60KB of base64 per widget made the editor's code highlighting take seconds per
widget). Scripts are shipped base64-encoded,
because LessWrong's widget save path decodes HTML entities inside scripts (`&&gt(` became `&&>(`
in an earlier experiment). The <meta name="lw-layout"> tag stays first so it's easy to find.

Usage: python3 build.py
"""
import base64
import json
import pathlib
import re

HERE = pathlib.Path(__file__).parent
# ET Book from tufte-css on jsDelivr, which sends CORS headers, so the sandboxed widget frames can use it.
FONT_URL = "https://cdn.jsdelivr.net/gh/edwardtufte/tufte-css@1.8.0/et-book/et-book-roman-line-figures/et-book-roman-line-figures.woff"


def wrap_script(match: re.Match) -> str:
    code = base64.b64encode(match.group(1).encode()).decode()
    return ('<script>new Function(new TextDecoder().decode(Uint8Array.from(atob("%s"), c => c.charCodeAt(0))))()</script>'
            % code)


def main():
    shared = (HERE / "widgets/shared.css").read_text()
    head = ('<style>@font-face{font-family:"et-book";src:url(%s) format("woff");'
            'font-weight:normal;font-style:normal;font-display:swap}\n%s</style>' % (FONT_URL, shared))
    out = HERE / "out"
    out.mkdir(exist_ok=True)
    widgets = {}
    for widget in sorted((HERE / "widgets").glob("*.html")):
        html = widget.read_text()
        meta = re.search(r'<meta name="lw-layout"[^>]*>\n?', html)
        body = html.replace(meta.group(0), "") if meta else html
        body = re.sub(r"<script>([\s\S]*?)</script>", wrap_script, body)
        built = (meta.group(0).strip() if meta else "") + "\n" + head + "\n" + body
        (out / widget.name).write_text(built)
        widgets[widget.stem] = built
        print(f"{widget.name}: {len(built):,} bytes")
    # The same post and widgets as a module, so the server can recreate the demo post on its own
    # (see packages/lesswrong/server/layoutDemo/aiFuturesLayoutDemo.ts).
    fixture = ("// Generated by build.py from post.html and widgets/. Do not edit.\n"
               "export const AI_FUTURES_DEMO_POST_HTML: string = %s;\n"
               "export const AI_FUTURES_DEMO_WIDGETS: Record<string, string> = %s;\n"
               % (json.dumps((HERE / "post.html").read_text()), json.dumps(widgets, indent=1)))
    (HERE / "fixture.generated.ts").write_text(fixture)
    print(f"fixture.generated.ts: {len(fixture):,} bytes")


if __name__ == "__main__":
    main()
